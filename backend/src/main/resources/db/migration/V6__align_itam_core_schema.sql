CREATE OR REPLACE FUNCTION fn_validate_asset_license_expiry()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_term_code VARCHAR(50);
BEGIN
  SELECT code INTO v_term_code FROM license_term_types
  WHERE license_term_type_id = NEW.license_term_type_id;
  IF v_term_code = 'SUBSCRIPTION' AND NEW.expiry_date IS NULL THEN
    RAISE EXCEPTION 'SUBSCRIPTION license must have expiry_date';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_validate_asset_license_expiry
BEFORE INSERT OR UPDATE OF license_term_type_id, expiry_date
ON asset_license_details FOR EACH ROW
EXECUTE FUNCTION fn_validate_asset_license_expiry();

