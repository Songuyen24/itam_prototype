ALTER TABLE transaction_assets ADD COLUMN line_number INTEGER;
WITH numbered AS (
  SELECT transaction_asset_id,
         ROW_NUMBER() OVER (PARTITION BY transaction_id ORDER BY transaction_asset_id) AS rn
  FROM transaction_assets
)
UPDATE transaction_assets ta SET line_number = numbered.rn FROM numbered
WHERE ta.transaction_asset_id = numbered.transaction_asset_id;
